/**
 * Fetch neighborhood demographics
 *
 * @param input Neighborhood ID, name, city, coordinates, and optional date
 * @returns Neighborhood demographic metrics
 * @throws Error if neighborhood not found or parameters invalid
 */
export function neighborhoodDemographics(input: NeighborhoodMetricsInput): NeighborhoodMetrics {
  const { neighborhoodId, cityId, asOfDate } = input;

  const validatedDate = validateDateOrUseToday(asOfDate);

  // Look up mock data
  const mockData = MOCK_DATA[neighborhoodId];
  if (!mockData) {
    throw new Error(`Neighborhood "${neighborhoodId}" not found in data sources.`);
  }

  // Verify city matches
  if (mockData.cityId !== cityId) {
    throw new Error(
      `Neighborhood "${neighborhoodId}" belongs to city "${mockData.cityId}", ` +
      `but input specified city "${cityId}".`
    );
  }

  // Date matching (same logic as E29-E30)
  if (validatedDate.toDateString() !== mockData.asOfDate.toDateString()) {
    throw new Error(
      `No data available for neighborhood "${neighborhoodId}" on ${validatedDate.toISOString().split('T')[0]}. ` +
      `Latest data: ${mockData.asOfDate.toISOString().split('T')[0]}`
    );
  }

  return mockData;
}

export default neighborhoodDemographics;
